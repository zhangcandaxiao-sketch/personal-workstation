/** 用模板 + 公司名拼接完整提示词 */
export function buildDeclarationPrompt(
  company: string,
  tpl: PromptTemplate = DEFAULT_TEMPLATE
): string {
  const name = company.trim();
  return `${tpl.role.replace('{company}', name)}

【表格固定信息】
${tpl.fixedInfo}

【请严格按以下五个部分逐项输出，标题保持一致】
${tpl.section1}
${tpl.section2}
${tpl.section3}
${tpl.section4}
${tpl.section5}

【写作要求】
${tpl.requirements}

【格式与详略参考：以下为已填报示例，仅供把握栏目口径与写作粒度，切勿照抄其内容】
${tpl.examples}`;
}
