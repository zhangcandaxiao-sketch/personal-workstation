// ── 类型定义 ───────────────────────────────────────────────────────────
export type CategoryId =
  | 'ai' // AI / 科技大会、沙龙
  | 'exhibition' // 艺术展览、特展
  | 'show' // 演出 / 音乐会 / 演唱会
  | 'market' // 市集 / 嘉年华 / 展会
  | 'experience' // 沉浸式体验 / 夜游
  | 'science'; // 科普场馆 / 研学

export type SlotId = 'morning' | 'afternoon' | 'evening';

export interface EventSource {
  name: string;
  url: string;
}

export interface WEvent {
  id: string;
  title: string;
  category: CategoryId;
  /** 开始日期 ISO yyyy-mm-dd */
  startDate: string;
  /** 结束日期 ISO（含当天），缺省为单日 */
  endDate?: string;
  /** 具体时刻/场次说明 */
  timeHint?: string;
  venue: string;
  /** 区域（用于动线聚类），尽量填到单区 */
  district: string;
  address?: string;
  /** 价格说明 */
  price: string;
  free: boolean;
  /** 是否需要预约/购票/报名 */
  booking?: boolean;
  /** 闭馆日（JS getDay：周一=1 … 周日=0） */
  closedWeekdays?: number[];
  highlights: string[];
  tags: string[];
  source: EventSource;
  /** 典型游玩时长（小时） */
  durationHours: number;
  /** 适合安排的时段 */
  slots: SlotId[];
  /** 三维度打分（每项 1–5 分） */
  scores: {
    importance: number; // 重要：含金量 / 机会难得 / 值得专门去
    fun: number; // 有趣：好玩程度
    education: number; // 教育意义：学习 / 认知价值
  };
  /** 兜底活动：常驻博物馆 / 科技馆，仅当没有合适活动时才安排 */
  fallback?: boolean;
  /** 同一活动在其他信源的链接（实时抓取合并时产生） */
  otherSources?: EventSource[];
}

export interface CategoryMeta {
  label: string;
  icon: ComponentType<{ className?: string }>;
  /** 图标底色 + 图标色 */
  iconWrap: string;
  /** 徽章色 */
  badge: string;
}

