export type DayKind = 'workday' | 'holiday';

function getYearData(y: number): YearData {
  return DATA[y] ?? { holidays: {}, makeupWorkdays: [] };
}

/** 判断某天是工作日还是休息日 */
export function getDayKind(y: number, m0: number, d: number): DayKind {
  const k = key(y, m0, d);
  const data = getYearData(y);
  if (data.holidays[k]) return 'holiday';
  if (data.makeupWorkdays.includes(k)) return 'workday';
  const wd = new Date(y, m0, d).getDay();
  return wd === 0 || wd === 6 ? 'holiday' : 'workday';
}

/** 节日名（如果当天是法定节假日） */
export function holidayName(y: number, m0: number, d: number): string | undefined {
  return getYearData(y).holidays[key(y, m0, d)];
}

/** 某年是否有"预估"备注 */
export function yearNote(y: number): string | undefined {
  return getYearData(y).note;
}
